import { createHash } from "node:crypto";
import Link from "next/link";
import AcceptInvitationForm from "@/app/ui/students/accept-invitation-form";
import { sql } from "@/app/lib/db";

export const dynamic = "force-dynamic";

type InvitationRow = {
  status: string;
  expired: boolean;
  tutorName: string;
  studentName: string;
  inviteeEmail: string;
};

type PageProps = {
  searchParams: Promise<{
    token?: string | string[];
  }>;
};

function MessageCard({
  title,
  message,
  showLogin = false,
}: {
  title: string;
  message: string;
  showLogin?: boolean;
}) {
  return (
    <section className="w-full max-w-lg rounded-[28px] border border-zinc-200 bg-white p-8 sm:p-10">
      <h1 className="text-2xl font-semibold tracking-tight text-zinc-900">
        {title}
      </h1>

      <p className="mt-4 text-sm leading-7 text-zinc-500">
        {message}
      </p>

      {showLogin && (
        <Link
          href="/login"
          className="mt-8 inline-flex min-h-12 items-center justify-center
            rounded-xl bg-zinc-900 px-6 text-sm font-medium text-white
            transition-colors hover:bg-zinc-700
            focus-visible:outline-none focus-visible:ring-2
            focus-visible:ring-zinc-900 focus-visible:ring-offset-4"
        >
          Sign in
        </Link>
      )}
    </section>
  );
}

export default async function AcceptInvitationPage({
  searchParams,
}: PageProps) {
  const { token } = await searchParams;

  let invitation: InvitationRow | undefined;
  let lookupFailed = false;

  // Matches the 32-byte hexadecimal token generated by addStudent().
  const validTokenFormat =
    typeof token === "string" && /^[a-f0-9]{64}$/i.test(token);

  if (validTokenFormat) {
    const tokenHash = createHash("sha256")
      .update(token)
      .digest("hex");

    try {
      const rows = await sql`
        SELECT
          invitation.status,
          invitation.expires_at <= now() AS expired,
          COALESCE(
            NULLIF(btrim(teacher.name), ''),
            'Your tutor'
          ) AS "tutorName",
          student.name AS "studentName"
          invitation.invitee_email AS "inviteeEmail",

        FROM invitations AS invitation

        JOIN teacher_student_connections AS connection
          ON connection.id = invitation.connection_id

        JOIN teachers AS teacher
          ON teacher.id = connection.teacher_id

        JOIN students AS student
          ON student.id = connection.student_id

        WHERE invitation.token_hash = ${tokenHash}

        LIMIT 1
      `;

      invitation = rows[0] as InvitationRow | undefined;
    } catch {
      // Never log the raw invitation token.
      lookupFailed = true;
    }
  }

  let content;

  if (lookupFailed) {
    content = (
      <MessageCard
        title="We couldn’t check your invitation"
        message="Please refresh this page and try again in a moment."
      />
    );
  } else if (!invitation) {
    content = (
      <MessageCard
        title="This invitation isn’t valid"
        message="Open the complete link from your invitation email. If it still doesn’t work, ask your tutor to send you a new invitation."
      />
    );
  } else if (invitation.status === "accepted") {
    content = (
      <MessageCard
        title="You’ve already accepted"
        message="This invitation has already been used. Sign in to continue to your account."
        showLogin
      />
    );
  } else if (invitation.status === "cancelled") {
    content = (
      <MessageCard
        title="This invitation was cancelled"
        message="Please contact your tutor if you would still like to join."
      />
    );
  } else if (
    invitation.status === "expired" ||
    invitation.expired
  ) {
    content = (
      <MessageCard
        title="Your invitation has expired"
        message="Invitations are valid for 24 hours. Ask your tutor to send you a new invitation."
      />
    );
  } else if (invitation.status !== "pending") {
    content = (
      <MessageCard
        title="This invitation is unavailable"
        message="Please contact your tutor for a new invitation."
      />
    );
  } else {
    content = (
      <section className="w-full max-w-lg rounded-[28px] border border-zinc-200 bg-white p-8 sm:p-10">
        <div
          aria-hidden="true"
          className="flex h-16 w-16 items-center justify-center
            rounded-full bg-violet-100 text-2xl font-medium text-violet-700"
        >
          {invitation.studentName.trim().charAt(0).toUpperCase() || "S"}
        </div>

        <p className="mt-7 text-sm text-zinc-500">
          Hello, {invitation.studentName}
        </p>

        <h1 className="mt-2 text-3xl font-semibold leading-tight tracking-tight text-zinc-900">
          {invitation.tutorName} invited you to TutorFlow
        </h1>

        <p className="mt-5 text-sm leading-7 text-zinc-500">
          Keep your lessons, homework, and lesson confirmations
          together in one place.
        </p>

        {typeof token === "string" && (
        <AcceptInvitationForm
            token={token}
            email={invitation.inviteeEmail}
        />
        )}
      </section>
    );
  }

  return (
    <main className="flex min-h-screen flex-col bg-white px-6 py-8 sm:px-10">
      <header>
        <span className="text-xl font-semibold tracking-tight text-zinc-900">
          TutorFlow.
        </span>
      </header>

      <div className="flex flex-1 items-center justify-center py-14">
        {content}
      </div>

      <footer className="text-center text-xs text-zinc-400">
        Your learning, organised.
      </footer>
    </main>
  );
}